import { ExtLink } from "../../components/ExtLink.tsx";
import { Page } from "../../components/Page.tsx";
import { allDocs } from "../../lib/docs.ts";
import { pageMeta } from "../../lib/meta.ts";
import { sourceUrl } from "../../site.config.ts";

export const metadata = pageMeta({
  title: "Documentation",
  description: "The MELOPHOS documentation: the protocol, the scoring engine, instruments, self-hosting and the decisions behind the design.",
  path: "/docs/",
});

const groupId = (group: string): string => `g-${group}`.replace(/\s+/g, "-").toLowerCase();

export default function Docs() {
  const docs = allDocs();
  const groups = [...new Set(docs.map((d) => d.group))];
  return (
    <Page path="/docs/" section="docs">
      <h1 className="page-title">Documentation</h1>
      <p className="lead lead-wide">The project's documents, shown here as they are written in the repository. There is one copy of each and this site reads it.</p>
      <p className="prose">
        Where a document describes a feature, the <a href="/roadmap/">roadmap</a> says whether it is built. The API reference is generated by a running server and is not on this site.
      </p>
      {groups.map((group) => (
        <section className="section" aria-labelledby={groupId(group)} key={group}>
          <h2 id={groupId(group)}>{group}</h2>
          <ul className="rows">
            {docs
              .filter((d) => d.group === group)
              .map((d) => (
                <li className="row row-wide" key={d.slug}>
                  <p className="name"><a href={d.route}>{d.title}</a></p>
                  <p>{d.summary}</p>
                </li>
              ))}
          </ul>
        </section>
      ))}
      <p className="prose">
        The <ExtLink href={sourceUrl("assets/brand", "tree")}>brand files</ExtLink> stay in the repository.
      </p>
    </Page>
  );
}
